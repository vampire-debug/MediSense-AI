import streamlit as st
import pandas as pd
import joblib
import plotly.graph_objects as go

from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
from reportlab.lib.styles import getSampleStyleSheet
from io import BytesIO


# ======================================
# Load Model Files
# ======================================

model = joblib.load("models/pcos_model.pkl")
features = joblib.load("models/features.pkl")
defaults = joblib.load("models/default_values.pkl")

comparison = pd.read_csv(
    "reports/model_comparison.csv"
)



# ======================================
# PDF Generator
# ======================================

def generate_pdf(
        risk,
        probability,
        explanation,
        recommendations
):

    buffer = BytesIO()

    doc = SimpleDocTemplate(buffer)

    styles = getSampleStyleSheet()

    content = []


    content.append(
        Paragraph(
            "MediSense AI - PCOS Risk Report",
            styles["Title"]
        )
    )

    content.append(
        Spacer(1,20)
    )


    content.append(
        Paragraph(
            f"Risk Level: {risk}",
            styles["Normal"]
        )
    )


    content.append(
        Paragraph(
            f"Risk Probability: {probability:.2f}%",
            styles["Normal"]
        )
    )


    content.append(
        Spacer(1,20)
    )


    content.append(
        Paragraph(
            "Patient Factors:",
            styles["Heading2"]
        )
    )


    for key,value in explanation.items():

        content.append(
            Paragraph(
                f"{key}: {value}",
                styles["Normal"]
            )
        )


    content.append(
        Spacer(1,20)
    )


    content.append(
        Paragraph(
            "Recommendations:",
            styles["Heading2"]
        )
    )


    for item in recommendations:

        content.append(
            Paragraph(
                "• " + item,
                styles["Normal"]
            )
        )


    content.append(
        Spacer(1,20)
    )


    content.append(
        Paragraph(
            "Generated by MediSense AI",
            styles["Normal"]
        )
    )


    doc.build(content)

    buffer.seek(0)

    return buffer



